-- ============================================================
-- M1 树洞/匿名帖(2026-10-25)
-- 设计要点:
-- 1. post 表加 is_anonymous 标记,只影响展示层(作者不下发),DB 永远存真实 author_id
--    ——管理端实锤(审核队列/举报处置/操作日志)读的是原值,零改动。
-- 2. 匿名帖在「他人主页帖子列表」整条排除(否则列表本身即泄露作者);
--    本人视角(/post/mine)保留,靠 PostVO.mine 维持编辑/删除能力。
-- 3. 匿名标记创建时一次定终身,编辑不可翻转(已被人看到的匿名身份不应可追溯)。
-- ============================================================
ALTER TABLE post ADD COLUMN is_anonymous TINYINT NOT NULL DEFAULT 0
    COMMENT '树洞匿名帖 0否1是(作者不出现在任何展示出口,管理端可见)' AFTER is_top;
