--   引流词只收短语(加微信/vx),不收「微信」裸词——正常社交不误伤
--
-- 谐音变体(薇信/薇芯)显式入库:TextNormalizer 只归一化字符级变体
-- (全角/零宽/拆字空格),谐音属词义级变体,归词库管——这是代码与词库的分界。
--
-- 涉政人名类**刻意不收**:该类名单必须从合规供应商处获取并持续维护,
-- 手工零散补几条反而造成「已覆盖」的假象。
--
-- 幂等:sensitive_word 有 uk_word 唯一键,INSERT IGNORE 可重复执行。
--
-- 执行:
--   mysql -uroot -p --default-character-set=utf8mb4 campus_social_v2 < sql/migration_sensitive_words.sql
-- 生效:SensitiveWordRefreshTask 每 5 分钟自动重载 DFA,无需重启;
