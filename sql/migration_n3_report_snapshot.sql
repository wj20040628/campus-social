-- 举报快照（2026-10-29）
--
-- 背景：举报只存 target_id，管理端打开举报时现场查原内容；作者在管理员
-- 处置前删帖（物理删除）、删评论/撤回消息（软删）后，管理员只剩
-- 「内容已删除或不存在」，无法核实举报是否成立。
--
-- 本列在举报提交时写入目标快照（JSON：标题/正文/作者/媒体/时间），
-- 只给管理端看；历史举报保持 NULL，按现有逻辑显示「已删除」。
ALTER TABLE `report`
    ADD COLUMN `target_snapshot` TEXT NULL COMMENT '举报时目标快照(JSON: 标题/正文/作者/媒体/时间)' AFTER `reason_text`;
