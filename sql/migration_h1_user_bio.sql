-- 用户个人介绍 bio（2026-10-19）
-- 用途：主页头像下方展示，取代原先展示脱敏学号的位置。
-- 安全动因：学号结构是「入学年份+专业大类+专业位+班级」，
-- 脱敏形态 2308****0678 仍泄露前三段，足以反推并冒充；
-- bio 是公开、无敏感信息、又能说明「你是谁」的字段。
--
-- 长度 200：主页身份头下方最多显示两行，更长会被截断，
-- 而用户不会知道自己的介绍只露出一半。

ALTER TABLE user
    ADD COLUMN bio VARCHAR(200) NULL COMMENT '个人介绍，NULL/空=还没写' AFTER nickname;